"""Generate the LaTeX tables of the revision from the result CSVs.

Every number that goes into the response letter or the revised manuscript is
produced here, never copied by hand.  Rerun after any new experiment lands in
``result/``; the letter and the manuscript pick the fragments up via ``\\input``.

Usage (from the repository root)::

    python -m paper_assets.make_tables            # -> paper_assets/tables/*.tex

Each fragment is a bare ``tabular`` plus a comment header naming its source
files, so the surrounding ``table`` environment (caption, label, colour) stays
under the author's control in the document that includes it.
"""
from __future__ import annotations

import glob
import os
import sys

import pandas as pd

try:
    from scipy import stats as scipy_stats
except ImportError:  # pragma: no cover
    scipy_stats = None

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables")
RULES = ["MQ-ND", "MQ-MinRQ", "MQ-MI", "MI-MinRQ", "MI-MI"]


def load(pattern: str) -> pd.DataFrame:
    paths = sorted(glob.glob(f"result/{pattern}/eval_results.csv"))
    if not paths:
        return pd.DataFrame()
    frames = []
    for path in paths:
        frame = pd.read_csv(path)
        frame["src"] = path.split(os.sep)[1]
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def fmt(value, digits=1) -> str:
    return "--" if pd.isna(value) else f"{value:.{digits}f}"


def mean_std(series: pd.Series, digits=1) -> str:
    if len(series) == 0:
        return "--"
    if len(series) == 1 or series.std(ddof=1) < 1e-9:
        return fmt(series.mean(), digits)
    return f"{series.mean():.{digits}f} $\\pm$ {series.std(ddof=1):.{digits}f}"


def write(name: str, sources: list, lines: list) -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, name)
    header = ["% Generated by paper_assets/make_tables.py -- do not edit by hand.",
              "% Sources: " + ", ".join(sources)]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(header + lines) + "\n")
    print(f"  -> {path}")


